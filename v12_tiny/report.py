"""Render every saved result into RESULTS.md (tables only; prose lives in v12_Architecture.md).

  python -B report.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RUNS = ROOT / 'runs'


def j(p):
    try: return json.loads(p.read_text())
    except Exception: return None


def f(x, n=3):
    return '—' if x is None else (f'{x:.{n}f}' if isinstance(x, float) else str(x))


def main():
    out = ['# V12 tiny — result tables (generated by report.py)', '']
    runs = sorted(p.name for p in RUNS.iterdir() if (p / 'manifest.json').exists() and not p.name.startswith('pilot'))
    # Phase 1
    out += ['## Phase 1 — dev NLL, concept usage, competence', '',
            '| run | ckpt | pinpad act NLL | text NLL | math NLL | newmath NLL | text Δoff | math Δoff | pinpad act Δoff | competence (any task) | post raw |',
            '|---|---|---|---|---|---|---|---|---|---|---|']
    for r in runs:
        for e in sorted((RUNS / r).glob('eval_*.json')):
            d = j(e)
            if not d: continue
            b = d.get('bpe_nll', {}); off = d.get('bpe_nll_concept_off', {}); po = d.get('nll_concept_off', {})
            dt = (off.get('text') - b['text']) if off and b else None
            dm = (off.get('math') - b['math']) if off and b else None
            dp = (po.get('act') - d['nll']['act']) if po else None
            out.append(f"| {r} | {d.get('ckpt')} | {f(d['nll']['act'])} | {f(b.get('text'))} | {f(b.get('math'))} | {f(b.get('newmath'))} | "
                       f"{f(dt)} | {f(dm)} | {f(dp)} | {f(d.get('competence_any'))} | {f(d.get('post_success_raw'))} |")
    # Probes
    out += ['', '## Probes (probe_diag): accuracy by depth; ECD rows add the concept stream (u, then concept states)', '']
    for r in runs + ['pilot_TF_d128']:
        for e in sorted((RUNS / r).glob('probe_diag_*.json')):
            d = j(e)
            if not d: continue
            out.append(f"**{r} / {e.stem.replace('probe_diag_', '')}** — {d.get('layers', '')}")
            out.append('')
            n = len(d['abs'])
            cols = ([f'e{i}' for i in range(n - 3)] + ['u', 'c1', 'c2']) if 'concept' in d.get('layers', '') else [f'e{i}' for i in range(n)]
            out.append('| latent (chance) | ' + ' | '.join(cols) + ' |')
            out.append('|---|' + '---|' * len(d['abs']))
            for k in ('abs', 'col', 'parity', 'last', 'cell'):
                if k in d: out.append(f"| {k} ({d[k + '_chance']}) | " + ' | '.join(f'{x:.3f}' for x in d[k]) + ' |')
            if 'effective_rank' in d: out.append('| effective rank | ' + ' | '.join(f'{x:.1f}' for x in d['effective_rank']) + ' |')
            out.append('')
    # GT controllers
    out += ['## Phase 2a — ground-truth controllers (Fig. 4)', '',
            '| run | point | act NLL base → GT | post (12-colour) GT / base | 3-pair novel GT / base | pretrain tasks GT |', '|---|---|---|---|---|---|']
    for r in runs + ['pilot_TF_d128']:
        for e in sorted((RUNS / r).glob('gtctrl_*.json')):
            d = j(e)
            if not d: continue
            out.append(f"| {r} | {d['ctrl_point']} | {f(d['dev_meta_act_nll_base'])} → {f(d['dev_meta_act_nll_gt'])} | {f(d['post_success_gt'])} / {f(d['post_success_base'])} | "
                       f"{f(d.get('short_success_gt'))} / {f(d.get('short_success_base'))} | {f(d['pretrain_success_gt'])} |")
    # Metacontroller
    out += ['', '## Phase 2b — metacontroller (dev_meta): rate–distortion and switch alignment', '',
            '| run | point | α | steps | NLL (distortion) | rate (KL/action) | pair F1 ±2 (chance) | pair P / R | colour F1 ±2 (chance) | switches/ep (true pair 2, colour 5) | mean β | frac β∈(.1,.9) |',
            '|---|---|---|---|---|---|---|---|---|---|---|---|']
    for r in runs + ['pilot_TF_d128']:
        md = RUNS / r / 'meta'
        if not md.exists(): continue
        rows = []
        for e in md.glob('*.json'):
            d = j(e)
            if d and 'eval' in d: rows.append(d)
        for d in sorted(rows, key=lambda d: (d['ctrl_point'], d['alpha'], d['seed'])):
            ev = d['eval']
            ch = d.get('chance', {}) if ev['switches_per_ep'] > 0 else {}     # chance undefined with zero switches
            out.append(f"| {r} | {d['ctrl_point']} | {d['alpha']} | {d.get('steps')} | {f(ev['nll'])} | {f(ev['rate'], 4)} | {f(ev['f1'])} ({f(ch.get('pair_f1_chance'))}) | {f(ev['precision'], 2)} / {f(ev['recall'], 2)} | "
                       f"{f(ev.get('colour_f1'))} ({f(ch.get('colour_f1_chance'))}) | {f(ev['switches_per_ep'], 2)} | {f(ev['mean_beta'], 2)} | {f(ev['frac_intermediate'], 2)} |")
    out += ['', '## XM codes on the frozen VAE switches (Step 6.2 ablation)', '']
    for r in runs + ['pilot_TF_d128']:
        for e in sorted((RUNS / r / 'meta').glob('xm_*.json')) if (RUNS / r / 'meta').exists() else []:
            d = j(e)
            if d: out.append(f"- {r} {e.stem}: hindsight-best NLL {f(d['dev_nll_hindsight_best'])}, rate (log K bound) {f(d.get('rate_logK'), 4)}, "
                             f"segments/ep {f(d.get('segments_per_ep'), 2)}, code usage {d['dev_code_usage']}")
    out += ['', '## Information test (Decision 3.4): next-segment code accuracy from u_g vs C input', '',
            '| run | family | codebook | dev rows | u_g MLP (linear) | p_g MLP (linear) | [p_g-1; p_g] MLP (linear) | NCP head | copy | majority |', '|---|---|---|---|---|---|---|---|---|---|']
    for r in runs:
        for e in sorted((RUNS / r).glob('info_test_*.json')):
            d = j(e)
            if not d: continue
            for fam, x in d.items():
                if not isinstance(x, dict): continue
                out.append(f"| {r} | {fam} | {d.get('codebook_from', r)} | {x.get('rows_dev', x.get('rows'))} | {f(x.get('mlp_u'))} ({f(x['acc_u'])}) | {f(x.get('mlp_p'))} ({f(x['acc_p'])}) | {f(x.get('mlp_p2'))} ({f(x.get('acc_p2'))}) | "
                           f"{f(x.get('acc_ncp_head'))} | {f(x['acc_copy'])} | {f(x['acc_majority'])} |")
    out += ['', '## Concept usage (Δ NLL with the concept route zeroed; used if ≥ 0.02)', '']
    for rr in runs:
        for e in sorted((RUNS / rr).glob('usage_*.json')):
            d = j(e)
            if d: out.append(f"- {rr} {d['ckpt']}: pinpad act {d['pinpad']['delta_act']:+.3f}, text {d['text']['delta']:+.3f}, "
                             f"math {d['math']['delta']:+.3f}, newmath {d['newmath']['delta']:+.3f}; used = {d['used']}")
    # Gradient share
    out += ['', '## Gradient share (aux / NTP gradient norm)', '']
    for r in runs:
        for e in sorted((RUNS / r).glob('grad_share_*.json')):
            out.append(f"- {r} {e.stem}: `{json.dumps(j(e))}`")
    # RL
    out += ['', '## Phase 3 — RL', '']
    for r in runs:
        rd = RUNS / r / 'rl'
        if not rd.exists(): continue
        for e in sorted(rd.glob('*.json')):
            d = j(e); h = d['hist']
            out.append(f"- {r} {e.stem}: first-5 success {sum(x['success'] for x in h[:5]) / max(len(h[:5]), 1):.3f}, "
                       f"last-5 {sum(x['success'] for x in h[-5:]) / max(len(h[-5:]), 1):.3f}, iterations {len(h)}")
    (ROOT / 'RESULTS.md').write_text('\n'.join(out) + '\n'); print('\n'.join(out[:12]))


if __name__ == '__main__':
    main()
