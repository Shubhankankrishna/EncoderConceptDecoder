def dump(path, value):
    p = ROOT / path
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + '\n')


def dump_lines(path, rows):
    p = ROOT / path
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open('w') as out:
        for row in rows:
            out.write(json.dumps(row, ensure_ascii=False, sort_keys=True, allow_nan=False) + '\n')


def rows(path):
    with (ROOT / path).open() as f:
        return [json.loads(line) for line in f if line.strip()]


def git_files():
    out = subprocess.check_output(['git', 'ls-files', '-z'], cwd=ROOT)
    return [os.fsdecode(p) for p in out.split(b'\0') if p]


def digest(p):
    if p.is_symlink():
        return hashlib.sha256(os.readlink(p).encode()).hexdigest()
    h = hashlib.sha256()
    with p.open('rb') as f:
        for chunk in iter(lambda: f.read(4 * 1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def load_small(path):
    p = ROOT / path
    try:
        if p.stat().st_size <= LIMIT:
            return json.loads(p.read_text())
    except (OSError, ValueError, UnicodeError):
        pass
    return None


def compact(value, depth=0):
    """Describe large result payloads while retaining scalar summary readings."""
    if isinstance(value, dict):
        if depth >= 4:
            return {'type': 'object', 'keys': list(value)[:30], 'key_count': len(value)}
        if len(value) > 60:
            return {'type': 'object', 'key_count': len(value), 'keys_sample': list(value)[:30]}
        return {k: compact(v, depth + 1) for k, v in value.items()}
    if isinstance(value, list):
        return {'type': 'array', 'length': len(value)}
    if isinstance(value, float) and not (-float('inf') < value < float('inf')):
        return str(value)
    if isinstance(value, str):
        return value[:400]
    return value


def walk():
    for base, dirs, files in os.walk(ROOT, followlinks=False):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and 'compiler_cache' not in d)
        for name in list(dirs):
            p = Path(base) / name
            if p.is_symlink():
                yield p.relative_to(ROOT).as_posix(), p
                dirs.remove(name)
        for name in sorted(files):
            p = Path(base) / name
            yield p.relative_to(ROOT).as_posix(), p


def exclusion(path, p):
    watchdog_output = path.startswith('v9_tiny/monitor/') and len(Path(path).parts) == 3 and p.name in {'state.json', 'status.json', 'watch.log', 'watch.log.1', 'alerts.log', 'ALERT.txt', 'watch.pid', 'STOP'}
    if watchdog_output or path.startswith(('v14_tiny/observatory/runtime/', 'v15_astra_v3/telemetry/runtime/')) or (path.startswith('v13_tiny/telemetry/') and p.name != 'index.html'):
        return 'live telemetry/runtime output; generated by the existing service'
    if path.startswith('v15_astra_m2/references/'):
        return 'temporary upstream checkout; restore the pinned source separately'
    if path.startswith(('v15_astra_m2/', 'v15_astra_v3/', 'v15_astra_ncm_v4/')) and p.name in {
            'texts.json', 'episodes.jsonl', 'problems.json', 'examples.json',
            'documents.json', 'documents.jsonl', 'graphs.json', 'records.json'}:
        return 'bulk dataset bodies or sealed examples; retain manifests and generators'
    if p.name == '.DS_Store' or p.name.startswith('._'):
        return 'operating-system metadata'
    if p.name.startswith('.env') or p.name in {'.netrc', 'credentials.json', 'token.json', 'id_rsa', 'id_ed25519'}:
        return 'private machine configuration'
    if p.suffix in {'.pyc', '.pyo', '.pid', '.lock', '.tmp'}:
        return 'runtime/cache file'
    if p.suffix.lower() == '.pdf':
        return 'reference paper; cite rather than redistribute'
    if path.startswith('tmp/'):
        return 'temporary literature/upstream research material'
    if p.suffix.lower() in ARTIFACT_EXTS or '.sqlite' in p.name:
        return 'local binary research artifact'
    if p.is_symlink():
        target = (p.parent / os.readlink(p)).resolve()
        if not target.is_relative_to(ROOT):
            return 'symlink outside the project'
        if not target.exists():
            return 'broken local symlink'
    if p.stat().st_size > LIMIT:
        return 'larger than 10 MiB'
    if any(part in {'data', 'data_v9', 'raw_tinystories'} for part in p.parts) and p.suffix in {'.jsonl', '.txt'}:
        return 'bulk dataset text or example/hash collection'
    if any(part in {'data', 'data_v9', 'raw_tinystories'} for part in p.parts) and p.name.endswith('_documents.json'):
        return 'bulk dataset document collection'
    return None


def family_for(path, families):
    for family in families:
        if any(path == prefix or path.startswith(prefix.rstrip('/') + '/') for prefix in family['paths']):
            return family['id']
    return 'project-context'


def link(path, prefix=''):
    return f'[{path}]({prefix}{quote(path, safe="/")})'


def extract_metrics(data):
    if not isinstance(data, dict):
        return {}
    keys = {'step', 'steps', 'tokens', 'elapsed_h', 'reasoning', 'text_nll', 'loss', 'status',
            'completed', 'success', 'accuracy', 'acc', 'seed', 'params', 'hours', 'budget_s'}
    return {k: compact(v) for k, v in data.items() if k in keys}


def discover_runs(files, families):
    groups = collections.defaultdict(list)
    for record in files:
        path = record['path']
        parts = Path(path).parts
        # Frozen audit copies are indexed as files, not counted as independent runs.
        if any(x in parts for x in {'source_snapshot', 'frozen', 'archive', 'snapshot', 'source'}):
            continue
        family = family_for(path, families)
        if family == 'project-context':
            continue
        if any(x in parts for x in {'runs', 'runs_q5_12h', 'validation', 'tests', 'experiments'}) or family in {'encoder', 'concept', 'decoder'}:
            parent = Path(path).parent.as_posix()
            # Flat legacy result/log files can identify separate seeded executions.
            if Path(path).suffix in {'.json', '.jsonl', '.log', '.out', '.txt'} and re.search(r'(?:^|_)s\d+(?:_|$)', Path(path).stem):
                parent = (Path(path).parent / Path(path).stem).as_posix()
            if family in {'concept', 'decoder'} and Path(path).name.startswith('RESULTS'):
                parent = (Path(path).parent / Path(path).stem).as_posix()
            if Path(path).suffix in {'.json', '.jsonl', '.pt', '.npz', '.log', '.out', '.txt'} or Path(path).name in {'DONE', 'ALL_DONE', 'PAUSE', 'phase2_done', 'post.done', 'launch.done'}:
                groups[(family, parent)].append(path)
    runs = []
    for (family, parent), paths in sorted(groups.items()):
        paths.sort()
        configs = [p for p in paths if Path(p).name in {'config.json', 'smoke_config.json', 'manifest.json', 'plan.json'}]
        results = [p for p in paths if (Path(p).suffix == '.json' and (any(x in Path(p).name.lower() for x in ('result', 'summary', 'eval', 'measure', 'comparison', 'diagnostic')) or Path(p).stem == Path(parent).name)) or Path(p).name.startswith('RESULTS')]
        checkpoints = [p for p in paths if p.endswith(('.pt', '.pth', '.ckpt'))]
        logs = [p for p in paths if p.endswith(('.jsonl', '.log', '.out'))]
        markers = [p for p in paths if Path(p).name in {'DONE', 'ALL_DONE', 'PAUSE', 'phase2_done', 'post.done', 'launch.done'}]
        status_sources = [p for p in paths if Path(p).name.startswith(('status', 'train_summary', 'summary')) and p.endswith('.json')]
        # A folder must have identifiable execution or evaluation evidence.
        if not (configs or results or checkpoints or markers or logs):
            continue
        seed = None
        for config in configs:
            data = load_small(config)
            if isinstance(data, dict):
                seed = data.get('seed', data.get('args', {}).get('seed') if isinstance(data.get('args'), dict) else None)
                if seed is not None:
                    break
        seed_source = 'configuration' if seed is not None else None
        match = re.search(r'(?:^|[_/])(?:s|seed)(\d+)(?:_|/|$)', parent)
        if seed is None and match:
            seed, seed_source = int(match.group(1)), 'directory name; confirm in configuration'
        state, reason = 'execution-recorded', 'Execution evidence exists; completion is not established.'
        statuses = []
        for p in status_sources:
            data = load_small(p)
            if isinstance(data, dict):
                statuses.append(str(data.get('status', '')))
        if any(s.startswith(('stopped', 'stop_requested', 'interrupted', 'failed', 'error')) for s in statuses) or any(Path(p).name == 'PAUSE' for p in markers) or '_aborted_' in parent:
            state, reason = 'interrupted', 'A saved stop/failure/pause status or aborted run name is present.'
        elif any(Path(p).name in {'DONE', 'ALL_DONE'} for p in markers) or any(s == 'complete' or s.startswith('completed') for s in statuses):
            state, reason = 'completed', 'An explicit saved completion marker/status is present.'
        elif 'slice_complete' in statuses:
            state, reason = 'partial-slice-completed', 'A bounded training slice finished; the full experiment is not established as completed.'
        elif results:
            state, reason = 'results-recorded', 'Saved evaluation/summary evidence exists; this does not establish all planned stages completed.'
        if any(x in parent.lower() for x in ('smoke', 'plumbing', 'bench', '/tmp_', '/tests', '/validation', 'pilot', 'throughput')):
            state, reason = 'smoke-or-engineering', 'Path identifies a smoke, pilot, validation, benchmark, or plumbing execution; not a final scientific experiment.'
        metrics = []
        for p in results[:12]:
            readings = extract_metrics(load_small(p))
            if readings:
                metrics.append({'source': p, 'readings': readings})
        available = [p for p in configs + results + markers if (ROOT / p).is_file() and exclusion(p, ROOT / p) is None]
        runs.append({'id': parent, 'family': family, 'status': state, 'status_reason': reason,
                     'seed': seed, 'seed_source': seed_source, 'configurations': configs,
                     'results': results, 'completion_markers': markers, 'status_sources': status_sources,
                     'logs': logs, 'checkpoint_paths': checkpoints, 'evidence_count': len(paths),
                     'published_evidence': sorted(set(available)), 'metrics': metrics,
                     'limitations': 'Folder-level inventory; nested stages and copied historical sources are not independent replications. Null metadata means unknown, not zero.'})
    return runs


def refresh():
    families = json.loads((ROOT / 'experiments/registry.json').read_text())['families']
    old = {r['path']: r for r in rows('artifacts/manifest.jsonl')} if (ROOT / 'artifacts/manifest.jsonl').exists() else {}
    artifacts, files, summaries, exact = [], [], [], []
    timestamp = dt.datetime.now(dt.timezone.utc).isoformat()
    for path, p in walk():
        if path in GENERATED or path.startswith(('docs/experiments/', 'docs/runs/')):
            continue
        reason = exclusion(path, p)
        stat = p.lstat()
        record = {'path': path, 'family': family_for(path, families), 'bytes': stat.st_size,
                  'disposition': 'local-only' if reason else 'git', 'reason': reason}
        files.append(record)
        if not reason:
            continue
        exact.append('/' + re.sub(r'([\\*?\[\]#! ])', r'\\\1', path))
        artifact = dict(record, mtime_ns=stat.st_mtime_ns)
        previous = old.get(path)
        if reason.startswith('live telemetry/'):
            artifact.update(sha256=None, hash_state='live')
        elif previous and previous.get('bytes') == stat.st_size and previous.get('mtime_ns') == stat.st_mtime_ns and previous.get('hash_state') == 'stable':
            artifact.update(sha256=previous['sha256'], hash_state='stable')
        else:
            checksum = digest(p)
            after = p.lstat()
            stable = (stat.st_size, stat.st_mtime_ns) == (after.st_size, after.st_mtime_ns)
            artifact.update(sha256=checksum if stable else None, hash_state='stable' if stable else 'changing')
        if p.is_symlink():
            artifact['symlink_target'] = os.readlink(p)
        artifacts.append(artifact)
        if reason == 'larger than 10 MiB' and p.suffix in {'.json', '.jsonl', '.log', '.out'} and '/data/' not in path:
            summary = {'path': path, 'family': record['family'], 'bytes': stat.st_size,
                       'sha256': artifact['sha256'], 'hash_state': artifact['hash_state'],
                       'local_only': True, 'limitation': 'Structural/scalar digest; read the original for full results.'}
            try:
                if p.suffix == '.json':
                    summary['summary'] = compact(json.loads(p.read_text()))
                else:
                    line_count = 0
                    first = last = ''
                    with p.open(errors='replace') as f:
                        for line in f:
                            if not first:
                                first = line[:500]
                            last = line[:500]
                            line_count += 1
                    summary.update(line_count=line_count, first_record=first, last_record=last)
            except (ValueError, OSError, UnicodeError) as exc:
                summary['summary_error'] = type(exc).__name__
            summaries.append(summary)
    ignore = ROOT / '.gitignore'
    text = ignore.read_text()
    start, end = '# BEGIN CATALOG EXCLUSIONS', '# END CATALOG EXCLUSIONS'
    text = text.split(start)[0] + start + '\n' + '\n'.join(sorted(exact)) + '\n' + end + '\n'
    ignore.write_text(text)
    dump_lines('artifacts/manifest.jsonl', artifacts)
    dump('artifacts/large_results.json', {'schema_version': 1, 'captured_at': timestamp, 'files': summaries})
    dump_lines('experiments/files.jsonl', files)
    baseline_path = ROOT / '.git/import-baseline.json'
    if baseline_path.exists() and not (ROOT / 'experiments/source_hashes.jsonl').exists():
        baseline = json.loads(baseline_path.read_text())
        published = {r['path'] for r in files if r['disposition'] == 'git'}
        dump_lines('experiments/source_hashes.jsonl', [r for r in baseline['files'] if r['path'] in published])
    runs = discover_runs(files, families)
    for family in families:
        family['runs_indexed'] = sum(r['family'] == family['id'] for r in runs)
        family['published_files'] = sum(r['family'] == family['id'] and r['disposition'] == 'git' for r in files)
        family['local_artifacts'] = sum(r['family'] == family['id'] and r['disposition'] == 'local-only' for r in files)
        family['provenance_files'] = [r['path'] for r in files if r['family'] == family['id'] and r['disposition'] == 'git' and Path(r['path']).name in {'manifest.json', 'environment.json', 'source_manifest.json', 'LOCK.json', 'baseline_manifest.json'}]
    catalog = {'schema_version': 1, 'captured_at': timestamp, 'status_policy': 'Evidence-based folder inventory; never infer completed training from a proposal or report header alone.',
               'excluded_cache_directories': sorted(SKIP_DIRS - {'.git'}) + ['*compiler_cache*'],
               'files_indexed': len(files), 'families': families, 'runs': runs}
    dump('experiments/catalog.json', catalog)
    render(catalog)
    print(json.dumps({'families': len(families), 'execution_groups': len(runs), 'published_candidates': sum(r['disposition'] == 'git' for r in files),
                      'local_artifacts': len(artifacts), 'local_bytes': sum(r['bytes'] for r in artifacts), 'large_result_digests': len(summaries)}, indent=2))


def render(catalog):
    lines = ['# Experiment chronology', '', f"Inventory captured {catalog['captured_at']}. These are present-day imports of preserved snapshots, not reconstructed historical Git commits.", '',
             'Read the saved configuration and evidence together. Versions use different datasets, budgets, tokenizers, and seeds; this is not a cross-version leaderboard.', '',
             '[Every indexed execution](docs/RUNS.md) · [Machine-readable catalog](experiments/catalog.json) · [Local artifact inventory](artifacts/manifest.jsonl) · [Working guide](docs/WORKFLOW.md)', '',
             '| Stage | Purpose | Evidence status | Execution groups | Start here |', '| --- | --- | --- | ---: | --- |']
    for family in catalog['families']:
        refs = ' · '.join(link(p) for p in family['reading'] if (ROOT / p).exists() and exclusion(p, ROOT / p) is None)
        lines.append(f"| {family['name']} | {family['purpose']} | {family['status']} | {family['runs_indexed']} | {refs} |")
    lines += ['', '## Interpretation notes', '']
    for family in catalog['families']:
        lines.append(f"- **{family['name']}:** {family['limitations']}")
    lines += ['', '## Preserved reports with stale status text', '',
              'Historical reports retain their original bytes. The entries below supplement their headers with saved evidence; they do not edit preregistrations.', '']
    for version in ['v13', 'v14']:
        result = f'{version}_tiny/runs/eval/base/results.json'
        data = load_small(result)
        if data:
            lines.append(f"- **{version.upper()}**: final base evaluation records step **{data.get('step')}**, **{data.get('tokens'):,} tokens**, reasoning score **{data.get('reasoning')}**, text NLL **{data.get('text_nll')}**. Source: {link(result)}. Check the run index for the separate continual stages.")
    lines += ['', '## Inventory limits', '',
              'Execution groups are directories containing saved execution/evaluation evidence, including engineering and interrupted work. A directory is not an independent experiment or training seed. Copied source snapshots are indexed as files and excluded from execution counts. Unknown seeds and settings remain null.', '',
              'Heavy files and downloaded papers are local-only. Their relative paths and checksums establish identity, not availability from GitHub. Dataset bodies and sealed examples are not embedded in this catalog.', '']
    (ROOT / 'EXPERIMENTS.md').write_text('\n'.join(lines))
    lines = ['# Saved execution groups', '', '[Chronology](../EXPERIMENTS.md) · [Full configurations, evidence paths, and scalar readings](../experiments/catalog.json)', '',
             'Statuses describe available evidence. `results-recorded` does not certify every intended training stage completed. Engineering/smoke/pilot runs are separated from final scientific evidence. Seeds inferred from names are labeled in the JSON catalog.', '']
    for family in catalog['families']:
        lines += [f"## {family['name']}", '', '| Execution directory | Status | Seed | Published evidence |', '| --- | --- | --- | --- |']
        for run in catalog['runs']:
            if run['family'] != family['id']:
                continue
            refs = ' · '.join(link(p, '../') for p in run['published_evidence'][:3]) or 'Logs or local artifacts; see catalog'
            seed = str(run['seed']) if run['seed'] is not None else 'unknown'
            if run['seed_source'] and run['seed_source'].startswith('directory'):
                seed += ' (name)'
            lines.append(f"| `{run['id']}` | {run['status']} | {seed} | {refs} |")
        lines.append('')
    (ROOT / 'docs').mkdir(exist_ok=True)
    (ROOT / 'docs/RUNS.md').write_text('\n'.join(lines))


def check(local=False):
    errors = []
    tracked = git_files()
    tracked_set = set(tracked)
    catalog = json.loads((ROOT / 'experiments/catalog.json').read_text())
    families = {f['id'] for f in catalog['families']}
    artifacts = {r['path']: r for r in rows('artifacts/manifest.jsonl')}
    files = rows('experiments/files.jsonl')
    indexed_paths = {r['path'] for r in files} | GENERATED
    registry = json.loads((ROOT / 'experiments/registry.json').read_text())['families']
    indexed_families = {f['id']: f for f in catalog['families']}
    for registered in registry:
        if any(indexed_families.get(registered['id'], {}).get(k) != v for k, v in registered.items()):
            errors.append('Registry changed without refreshing catalog: ' + registered['id'])
    syntax = 0
    for path in tracked:
        p = ROOT / path
        if path not in indexed_paths:
            errors.append('Tracked file missing from file inventory: ' + path)
        if not p.exists():
            errors.append('Missing tracked file: ' + path)
            continue
        if p.lstat().st_size > LIMIT:
            errors.append('Tracked file exceeds 10 MiB: ' + path)
        if exclusion(path, p):
            errors.append('Tracked file violates publication policy: ' + path)
        if p.suffix == '.py':
            try:
                ast.parse(p.read_bytes(), filename=path)
                syntax += 1
            except (ValueError, SyntaxError) as exc:
                errors.append(f'Python syntax: {path}: {exc}')
        if p.is_symlink():
            target = (p.parent / os.readlink(p)).resolve()
            target_path = target.relative_to(ROOT).as_posix() if target.is_relative_to(ROOT) else ''
            if not target_path or not (target_path in tracked_set or (target.is_dir() and any(t.startswith(target_path + '/') for t in tracked_set))):
                errors.append('Symlink target unavailable in clone: ' + path)
    for record in files:
        path = record['path']
        if record['disposition'] == 'git' and path not in tracked_set:
            errors.append('Publication candidate is untracked: ' + path)
        if record['disposition'] == 'local-only' and path not in artifacts:
            errors.append('Excluded research file has no artifact record: ' + path)
    for family in catalog['families']:
        for path in family['reading'] + family.get('status_evidence', []):
            if path not in tracked_set and path not in artifacts:
                errors.append('Missing family evidence: ' + path)
    ids = set()
    for run in catalog['runs']:
        if run['id'] in ids:
            errors.append('Duplicate execution ID: ' + run['id'])
        ids.add(run['id'])
        if run['family'] not in families:
            errors.append('Unknown family: ' + run['id'])
        for path in run['published_evidence']:
            if path not in tracked_set:
                errors.append('Unpublished linked evidence: ' + path)
    for record in rows('experiments/source_hashes.jsonl'):
        p = ROOT / record['path']
        if record['path'] not in tracked_set or not p.exists() or digest(p) != record['sha256']:
            errors.append('Historical source changed: ' + record['path'])
    imports = load_small('experiments/imports.json')
    if not isinstance(imports, dict) or not isinstance(imports.get('commits'), list):
        errors.append('Missing or invalid import history index')
    else:
        for number, record in enumerate(imports['commits'], 1):
            if record.get('sequence') != number:
                errors.append('Import sequence is not consecutive')
            revision = subprocess.run(['git', 'rev-parse', '--verify', record.get('commit', '') + '^{commit}'], cwd=ROOT, capture_output=True, text=True)
            if revision.returncode:
                errors.append('Missing import commit; fetch full history: ' + str(record.get('sequence')))
            if record.get('tag'):
                tagged = subprocess.run(['git', 'rev-parse', '--verify', 'refs/tags/' + record['tag'] + '^{commit}'], cwd=ROOT, capture_output=True, text=True)
                if tagged.returncode or tagged.stdout.strip() != record['commit']:
                    errors.append('Archival tag does not match import index: ' + record['tag'])
    # Check new navigation documents, preserving the old reports and their old links.
    for path in ['README.md', 'EXPERIMENTS.md', 'docs/RUNS.md', 'docs/WORKFLOW.md', 'docs/REPRODUCIBILITY.md', 'docs/GITHUB.md', 'docs/VALIDATION.md', 'docs/ASTRA_PROGRESS.md', 'docs/PUBLICATION_2026-10-20.md', 'artifacts/README.md', 'THIRD_PARTY_NOTICES.md']:
        p = ROOT / path
        if not p.exists():
            errors.append('Missing guide: ' + path)
            continue
        for target in re.findall(r'\]\(([^)]+)\)', p.read_text()):
            if '://' in target or target.startswith('#'):
                continue
            resolved = (p.parent / unquote(target.split('#')[0])).resolve()
            if not resolved.is_relative_to(ROOT) or resolved.relative_to(ROOT).as_posix() not in tracked_set:
                errors.append(f'Broken published guide link: {path}: {target}')
    if local:
        indexed = {r['path'] for r in files} | GENERATED
        for path, p in walk():
            if path not in indexed and path not in tracked_set:
                errors.append('Uncataloged local file: ' + path)
        for path, record in artifacts.items():
            p = ROOT / path
            if not p.exists():
                errors.append('Missing local artifact: ' + path)
                continue
            stat = p.lstat()
            if record['hash_state'] == 'stable' and (stat.st_size, stat.st_mtime_ns) != (record['bytes'], record['mtime_ns']):
                errors.append('Local artifact changed since inventory: ' + path)
    print(json.dumps({'tracked_files': len(tracked), 'python_files_parsed': syntax, 'families': len(families),
                      'execution_groups': len(ids), 'artifact_records': len(artifacts), 'errors': errors}, indent=2))
    return 1 if errors else 0


def scan():
    findings = []
    count = 0
    for path in git_files():
        p = ROOT / path
        if p.is_symlink():
            continue
        try:
            if p.suffix == '.docx':
                with zipfile.ZipFile(p) as document:
                    text = '\n'.join(ET.fromstring(document.read('word/document.xml')).itertext())
            else:
                text = p.read_text()
        except (UnicodeError, OSError, zipfile.BadZipFile, KeyError, ET.ParseError):
            continue
        count += 1
        for number, line in enumerate(text.splitlines(), 1):
            for kind, pattern in SECRETS.items():
                if pattern.search(line):
                    findings.append({'path': path, 'line': number, 'kind': kind})
    print(json.dumps({'text_files_scanned': count, 'findings': findings, 'limitation': 'Pattern scan; not a guarantee that arbitrary private information is absent.'}, indent=2))
    return bool(findings)


def verify_local_hashes():
    errors = []
    count = 0
    for record in rows('artifacts/manifest.jsonl'):
        p = ROOT / record['path']
        if record['hash_state'] != 'stable':
            continue
        if not p.exists() or digest(p) != record['sha256']:
            errors.append(record['path'])
        count += 1
    print(json.dumps({'artifact_checksums_verified': count, 'mismatches': errors}, indent=2))
    return bool(errors)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['refresh', 'check', 'check-local', 'scan', 'verify-local-hashes'])
    args = parser.parse_args()
    if args.command == 'refresh':
        refresh()
        return 0
    if args.command in {'check', 'check-local'}:
        return check(local=args.command == 'check-local')
    if args.command == 'scan':
        return int(scan())
    return int(verify_local_hashes())


if __name__ == '__main__':
    sys.exit(main())
