import time, math, torch, torch.nn.functional as F
dev = torch.device("mps"); torch.manual_seed(0)
N, d, E, k = 512, 256, 16, 2
x = torch.randn(N, d, device=dev); lg = torch.randn(N, E, device=dev)
def t(name, fn, n=30):
    for _ in range(3): y = fn()
    torch.mps.synchronize(); t0 = time.time()
    for _ in range(n): y = fn()
    torch.mps.synchronize(); print(f"{name:34s} {1000*(time.time()-t0)/n:6.3f} ms"); return y
probs = t("softmax", lambda: lg.softmax(-1))
gv, idx = t("topk", lambda: probs.topk(k, -1))
flat = idx.reshape(-1)
oh = t("one_hot int64", lambda: F.one_hot(flat, E))
t("cumsum int64", lambda: oh.cumsum(0))
t("cumsum float", lambda: oh.float().cumsum(0))
t("argsort", lambda: torch.argsort(flat, stable=True))
t("sort", lambda: torch.sort(flat, stable=True))
t("bincount", lambda: torch.bincount(flat, minlength=E))
src = torch.randint(0, N, (E*80,), device=dev)
t("gather rows x[src]", lambda: x[src])
t("index_select", lambda: x.index_select(0, src))
y = torch.randn(N*k, d, device=dev); nn_ = torch.arange(N, device=dev).repeat_interleave(k)
t("index_add", lambda: x.new_zeros(N, d).index_add(0, nn_, y))
w1 = torch.randn(E, d, 512, device=dev); xe = torch.randn(E, 80, d, device=dev)
t("bmm expert (E,80,256)x(256,512)", lambda: torch.bmm(xe, w1))
t("scatter", lambda: torch.full((E*80+1,), N, device=dev, dtype=torch.long).scatter(0, torch.randint(0, E*80, (N*k,), device=dev), nn_))
def top2(p):
    v1, i1 = p.max(-1)
    p2 = p.scatter(-1, i1.unsqueeze(-1), -1.0)
    v2, i2 = p2.max(-1)
    return torch.stack([v1, v2], -1), torch.stack([i1, i2], -1)
v, i = t("top2 via 2x max", lambda: top2(probs))
gv, idx = probs.topk(2, -1)
print("same as topk:", torch.equal(i, idx), torch.allclose(v, gv))
