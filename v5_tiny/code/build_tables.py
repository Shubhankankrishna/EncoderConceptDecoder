"""Collect every result JSON into RESULT_TABLES.md (numbers only; interpretation lives in REPORT.md)."""
import json
import os
import glob

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
RUNS = os.path.join(ROOT, "runs")


def J(path):
    try:
        return json.load(open(path))
    except Exception:
        return None


def f(x, n=3):
    return "—" if x is None else (f"{x:.{n}f}" if isinstance(x, (int, float)) else str(x))


def pm(d, n=3):
    if not d:
        return "—"
    return f"{d['delta']:+.{n}f} ± {d['se']:.{n}f}"


CORR = (J(os.path.join(RUNS, "oracle_text_correction.json")) or {}).get("text_correction", 0.0)


def fix_oracle(e):
    """Evaluations run before 15:33 omitted token positions 0..2 from oracle/mixture window sums (text only);
    add the exact correction (teacher NLL of those positions per row / scored tokens; identical for every mode)."""
    if e.get("oracle_window_fix"):
        return e
    for mode in ("oracle_best_of_8", "mixture_of_8_posthoc"):
        if mode in e.get("nll", {}):
            e["nll"][mode]["text"]["delta"] += CORR
            e["nll"][mode]["text"]["corrected"] = True
    return e


def main():
    L = ["# v5_tiny result tables", "", "Generated by `code/build_tables.py` from the JSON files in `runs/`.", ""]
    # ---------------- Phase A
    L += ["## Phase A", "", "| run | params | text NLL | graph NLL | colour | colour@switch | colour non-switch | node | greedy success | T=1 success |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for run in ("A_ncp_s0", "A_v0_s0"):
        e = J(os.path.join(RUNS, run, "eval_a_val.json")); ts = J(os.path.join(RUNS, run, "train_summary.json"))
        if not e:
            continue
        n = e["nll"]; ns = e["nll_split"]
        L.append(f"| {run} | {ts['params'] if ts else '—':,} | {f(n['text'])} | {f(n['graph'])} | {f(n['colour'])} | "
                 f"{f(n.get('colour_at_switch'))} | {f(n.get('colour_non_switch'))} | {f(ns['node'])} | "
                 f"{f(e['gen_greedy']['success'])} | {f(e['gen_t1']['success'])} |")
    e = J(os.path.join(RUNS, "A_ncp_s0", "eval_a_val.json"))
    if e and "route" in e:
        L += ["", "### Route authority (NCP s0; Δ NLL vs normal, paired SE over items)", "",
              "| intervention | text | graph | colour | colour@switch | colour non-switch |", "|---|---|---|---|---|---|"]
        for mode, r in e["route"].items():
            L.append(f"| {mode} | {pm(r['text'])} | {pm(r['graph'])} | {pm(r['colour'])} | {pm(r.get('colour_at_switch'))} | {pm(r.get('colour_non_switch'))} |")
        L += ["", f"Route gate (pre-registered, `mean`): {e['route_gate']}", ""]
        if "predicted_history" in e:
            ph = e["predicted_history"]
            L += [f"Predicted-concept history (NCP inference protocol) vs clean: text {pm(ph['text'])}, graph {pm(ph['graph'])}", ""]
        fc = e["forecast"]
        L += ["### Concept forecast MSE (per feature)", "", "| domain | NCP | copy-last | train-mean | linear |", "|---|---|---|---|---|"]
        for d, v in fc.items():
            L.append(f"| {d} | {f(v['ncp'])} | {f(v['copy'])} | {f(v['mean'])} | {f(v['linear'])} |")
        L += ["", f"Codebook: {e['codebook']['used']}/{e['codebook']['of']} codes used on val text; per-segment perplexity "
              + ", ".join(f"{p:.1f}" for p in e['codebook']['perplexity_per_segment']), ""]
    # ---------------- Phase B / C
    L += ["## Phases B and C (replacement cores; Δ vs the frozen NCP teacher on the same items)", "",
          "| run | variant | core params | mode | text Δ | graph Δ | colour Δ | gate |", "|---|---|---|---|---|---|---|---|"]
    for p in sorted(glob.glob(os.path.join(RUNS, "[BC]_*", "eval_b_val_lam1.0.json"))):
        e = fix_oracle(J(p)); run = os.path.basename(os.path.dirname(p))
        for mode, r in e["nll"].items():
            gate = e["gate"] if mode == e["gate"]["mode"] else ""
            L.append(f"| {run} | {e['variant']} | {e['core_params']:,} | {mode} | {pm(r['text'])} | {pm(r['graph'])} | {pm(r.get('colour'))} | {gate} |")
    L += ["", "### Control tests (GraphNav val, greedy tokens, pre-drawn noise)", "",
          "| run | hold4 success | resample success | hold4−resample | persistence hold4 / resample | Z-swap first colour differs | ε-only first colour differs | hold (stress) success | raw ‖h‖ per transition |",
          "|---|---|---|---|---|---|---|---|---|"]
    for p in sorted(glob.glob(os.path.join(RUNS, "[BC]_*", "eval_b_val_lam1.0.json"))):
        e = J(p); run = os.path.basename(os.path.dirname(p)); c = e.get("control", {})
        if not c:
            continue
        zs = c.get("zswap_first_colour_differs"); es = c.get("epsonly_first_colour_differs")
        L.append(f"| {run} | {f(c['hold4']['success'])} | {f(c['resample']['success'])} | {pm(c['hold4_minus_resample_success'])} | "
                 f"{f(c['hold4']['colour_persistence'])} / {f(c['resample']['colour_persistence'])} | "
                 f"{f(zs['rate']) if zs else '—'} | {f(es['rate']) if es else '—'} | {f(c['hold_stress']['success'])} | "
                 f"{', '.join(f(v, 2) for v in e['raw_h_norm_per_transition']) if e.get('raw_h_norm_per_transition') else '—'} |")
    L += ["", "### Replacement route split (deterministic path; Δ NLL vs normal)", "",
          "| run | text pq_mean | text crc_mean | graph pq_mean | graph crc_mean | colour@switch pq_mean | colour@switch crc_mean | hard-goal success (hold4) |",
          "|---|---|---|---|---|---|---|---|"]
    for p in sorted(glob.glob(os.path.join(RUNS, "[BC]_*", "eval_b_val_lam1.0.json"))):
        e = J(p); run = os.path.basename(os.path.dirname(p)); r = e.get("route_split")
        if not r:
            continue
        hg = e.get("hardgoal_hold4")
        L.append(f"| {run} | {pm(r['text_pq_mean']['nll'])} | {pm(r['text_crc_mean']['nll'])} | {pm(r['graph_pq_mean']['nll'])} | "
                 f"{pm(r['graph_crc_mean']['nll'])} | {pm(r['graph_pq_mean']['colour_at_switch'])} | {pm(r['graph_crc_mean']['colour_at_switch'])} | "
                 f"{(f(hg['success']) + ' ± ' + f(hg['se'])) if hg else '—'} |")
    blend = sorted(glob.glob(os.path.join(RUNS, "B_v6_s0", "eval_b_val_lam*.json")))
    if blend:
        L += ["", "### Blend curve (B_v6_s0; prior-sampled path)", "", "| λ | text Δ | graph Δ |", "|---|---|---|"]
        for p in blend:
            e = J(p); r = e["nll"].get("prior_sample") or e["nll"].get("det")
            L.append(f"| {e['lam']} | {pm(r['text'])} | {pm(r['graph'])} |")
    # ---------------- Phase D
    for p in sorted(glob.glob(os.path.join(RUNS, "D_*", "phase_d.json"))):
        e = J(p); run = os.path.basename(os.path.dirname(p))
        d = e["discovery"]
        L += ["", f"## Phase D: {run} (core {e['core_run']})", "",
              f"Discovery: soft NLL {f(d['soft'],4)}, hardened NLL {f(d['hard'],4)} (soft−hard {f(d['soft_minus_hard_nll'],4)}); "
              f"switch precision {f(d['switch_precision'])}, recall {f(d['switch_recall'])}; mean β at true switch {f(d['mean_beta_at_true_switch'])} "
              f"vs non-switch {f(d['mean_beta_at_non_switch'])}; fraction of β in (0.1, 0.9): {f(d['fraction_beta_intermediate'])}", "",
              ]
        for setname, ev in e["rollouts"].items():
            L += [f"**{setname} set**", "", "| controller | success ± SE | colour persistence | mean hops |", "|---|---|---|---|"]
            for k, v in ev.items():
                if isinstance(v, dict) and "success" in v:
                    L.append(f"| {k} | {f(v['success'])} ± {f(v['se'])} | {f(v.get('colour_persistence'))} | {f(v.get('mean_hops'),2)} |")
            for k, v in ev.items():
                if k.startswith("policy_minus"):
                    L.append(f"\n{k} (paired): {pm(v)}")
            L.append("")
    # ---------------- Phase E
    for p in sorted(glob.glob(os.path.join(RUNS, "E_*", "phase_e.json"))):
        e = J(p); run = os.path.basename(os.path.dirname(p))
        L += ["", f"## Phase E: {run} (core {e['core_run']}, set {e.get('set','standard')}, U={e['U']}, n={e['n']})", "",
              "| method | success within U+1 generations ± SE |", "|---|---|"]
        for k, v in e["success"].items():
            L.append(f"| {k} | {f(v['success'])} ± {f(v['se'])} |")
        L += ["", "| GradCuit arm | vs resample prior | vs token T=1 | vs random ΔZ |", "|---|---|---|---|"]
        for k, v in e["paired"].items():
            L.append(f"| {k} | {pm(v['vs_resample_prior'])} | {pm(v['vs_token_T1'])} | {pm(v['vs_random_dz'])} |")
        L.append(f"\nmean attempts: {e['mean_attempts']}; mean ‖ΔZ‖: {e['mean_dz_norm']}")
    open(os.path.join(ROOT, "RESULT_TABLES.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
