"""Data for v5_tiny: TinyStories text + GraphNav symbolic task, one 2048-entry tokenizer.

Text: TinyStories (local HF cache), ByteLevel BPE with 2048 entries, of which the first NSPEC are reserved specials
(pad, eos, GraphNav markers, node and colour tokens). Stories are concatenated with <eos> into one flat uint16 stream;
training rows are random T-token windows (standard packed LM training).

GraphNav (the symbolic task). One instance = one row of T=192 tokens, every decision exactly k=4 tokens:
  chunk 0        [<gnav>, goal, start, <sep>]
  chunks 1..30   [v, colour, f_colour(v), <sep>]   one per (node, colour), shuffled; N=10 nodes, 3 colours
  hops           [colour, <to>, node, <sep>]        node = f_colour(previous node)
  last chunk     [<done>, <sep>, <sep>, <sep>]
  then <pad>. Longest instance: 124 + 16*4 + 4 = 192 = T.
Each colour c is a random function f_c on the instance's nodes with no fixed points. The walk is generated by a
hidden rule sequence: 2-4 segments, each a colour held for 2-4 hops, consecutive colours distinct. The goal is the
final node (hindsight relabelling); instances whose walk visits the goal earlier (or starts there) are rejected, so
"stop at first arrival at the goal" is consistent with every demonstration.
Properties (review_v5 §9.3; advisor consult 1): (a) several valid continuations for a given prefix (which colour,
when to switch); (b) a hidden variable (current colour) that persists over several chunks and switches at
unpredictable points; (c) an exact verifier (graph + goal are in the header, no hidden answer is used).
Loss mask: only walk + done chunks are scored (the header is random and unlearnable).
"""
import os
import glob
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.normpath(os.path.join(HERE, "..", "data"))
TS_GLOB = os.path.expanduser("~/.cache/huggingface/hub/datasets--roneneldan--TinyStories/snapshots/*/data/")

N_NODE_TOK, N_COL = 24, 3
SPECIALS = (["<pad>", "<eos>", "<gnav>", "<sep>", "<to>", "<done>"]
            + [f"<n{i}>" for i in range(N_NODE_TOK)] + [f"<c{i}>" for i in range(N_COL)])
PAD, EOS, GNAV, SEP, TO, DONE = range(6)
NODE0 = 6
COL0 = NODE0 + N_NODE_TOK
NSPEC = len(SPECIALS)            # 33
VOCAB = 2048
T = 192
K = 4
N_NODES = 10
MAX_HOPS = 16
HEADER_CHUNKS = 1 + N_NODES * N_COL      # 31 chunks = 124 tokens
WALK_START = HEADER_CHUNKS * K           # token index of the first hop
HOP_FMT = os.environ.get("V5_HOP", "to")  # "to": [colour, <to>, node, <sep>]   "src": [cur, colour, node, <sep>]
                                          # "srcto": [cur, colour, node, <to>]  (header-mirroring offsets + walk cue)


# ----------------------------------------------------------------------------- tokenizer + text
def build_text(n_train_shards=1, seed=0):
    from tokenizers import Tokenizer, models, pre_tokenizers, decoders, trainers
    import pyarrow.parquet as pq
    os.makedirs(DATA, exist_ok=True)
    tok_path = os.path.join(DATA, "tokenizer.json")
    tr_files = sorted(glob.glob(TS_GLOB + "train-*.parquet"))[:n_train_shards]
    va_file = sorted(glob.glob(TS_GLOB + "validation-*.parquet"))[0]
    train_txt = [s for f in tr_files for s in pq.read_table(f).column("text").to_pylist()]
    val_txt = pq.read_table(va_file).column("text").to_pylist()
    if not os.path.exists(tok_path):
        rng = np.random.RandomState(seed)
        sample = [train_txt[i] for i in rng.choice(len(train_txt), 200000, replace=False)]
        tok = Tokenizer(models.BPE())
        tok.pre_tokenizer = pre_tokenizers.ByteLevel(add_prefix_space=False)
        tok.decoder = decoders.ByteLevel()
        trn = trainers.BpeTrainer(vocab_size=VOCAB, special_tokens=SPECIALS,
                                  initial_alphabet=pre_tokenizers.ByteLevel.alphabet(), show_progress=False)
        tok.train_from_iterator(sample, trn)
        tok.save(tok_path)
    tok = Tokenizer.from_file(tok_path)
    assert tok.get_vocab_size() == VOCAB, tok.get_vocab_size()
    for i, s in enumerate(SPECIALS):
        assert tok.token_to_id(s) == i
    for name, txt in (("train", train_txt), ("val", val_txt)):
        out = os.path.join(DATA, f"ts_{name}.npy")
        if os.path.exists(out):
            continue
        enc = tok.encode_batch([s.strip() for s in txt if s and s.strip()])
        parts = []
        for e in enc:
            parts.append(np.asarray(e.ids, dtype=np.uint16)); parts.append(np.array([EOS], dtype=np.uint16))
        flat = np.concatenate(parts)
        np.save(out, flat)
        print(f"{name}: {len(enc)} stories, {len(flat):,} tokens, {len(flat)/sum(len(s) for s in txt):.3f} tok/char")
    return tok


class TextStream:
    def __init__(self, split):
        self.flat = np.load(os.path.join(DATA, f"ts_{split}.npy"), mmap_mode="r")

    def batch(self, rng, B):
        st = rng.randint(0, len(self.flat) - T - 1, size=B)
        x = np.stack([self.flat[s:s + T] for s in st]).astype(np.int64)
        m = np.ones_like(x, dtype=np.float32)
        return x, m

    def fixed(self, n, seed):
        """Deterministic non-overlapping evaluation windows."""
        rng = np.random.RandomState(seed)
        st = np.sort(rng.choice(len(self.flat) // T - 1, n, replace=False)) * T
        return np.stack([self.flat[s:s + T] for s in st]).astype(np.int64)


# ----------------------------------------------------------------------------- GraphNav
def gen_graph(rng):
    labels = rng.choice(N_NODE_TOK, N_NODES, replace=False)
    f = np.zeros((N_COL, N_NODES), dtype=np.int64)
    for c in range(N_COL):
        for v in range(N_NODES):
            u = rng.randint(N_NODES - 1)
            f[c, v] = u + (u >= v)            # no fixed points
    return labels, f


def gen_rules(rng):
    nseg = rng.randint(2, 5)
    cols, durs, prev = [], [], -1
    for _ in range(nseg):
        c = rng.randint(N_COL - 1) if prev >= 0 else rng.randint(N_COL)
        if prev >= 0:
            c = c + (c >= prev)
        cols.append(c); durs.append(rng.randint(2, 5)); prev = c
    return cols, durs


def gen_instance(rng, max_tries=100):
    """Returns tokens [T], loss mask [T], meta dict. Node indices are instance-local 0..N-1."""
    for _ in range(max_tries):
        labels, f = gen_graph(rng)
        start = rng.randint(N_NODES)
        cols, durs = gen_rules(rng)
        nodes, hop_cols, seg_id, seg_pos = [start], [], [], []
        for si, (c, d) in enumerate(zip(cols, durs)):
            for j in range(d):
                nodes.append(f[c, nodes[-1]]); hop_cols.append(c); seg_id.append(si); seg_pos.append(j)
        goal = nodes[-1]
        if goal in nodes[:-1]:
            continue
        x = np.full(T, PAD, dtype=np.int64)
        x[0:4] = [GNAV, NODE0 + labels[goal], NODE0 + labels[start], SEP]
        edges = [(v, c) for v in range(N_NODES) for c in range(N_COL)]
        order = rng.permutation(len(edges))
        p = 4
        for e in order:
            v, c = edges[e]
            x[p:p + 4] = [NODE0 + labels[v], COL0 + c, NODE0 + labels[f[c, v]], SEP]; p += 4
        assert p == WALK_START
        for c, prev, u in zip(hop_cols, nodes[:-1], nodes[1:]):
            if HOP_FMT == "src":
                x[p:p + 4] = [NODE0 + labels[prev], COL0 + c, NODE0 + labels[u], SEP]
            elif HOP_FMT == "srcto":
                x[p:p + 4] = [NODE0 + labels[prev], COL0 + c, NODE0 + labels[u], TO]
            else:
                x[p:p + 4] = [COL0 + c, TO, NODE0 + labels[u], SEP]
            p += 4
        x[p:p + 4] = [DONE, SEP, SEP, SEP]; p += 4
        m = np.zeros(T, dtype=np.float32)
        m[WALK_START - 1:p - 1] = 1.0   # predict tokens WALK_START..p-1 (inputs at positions WALK_START-1..p-2)
        meta = dict(labels=labels, f=f, start=start, goal=goal, cols=cols, durs=durs, hop_cols=hop_cols,
                    seg_id=seg_id, seg_pos=seg_pos, n_hops=len(hop_cols))
        return x, m, meta
    raise RuntimeError("no instance")


def gen_hardgoal(rng, min_dist=4, max_tries=200):
    """Hard-goal OOD instance (pre-registered 11:20): same graph/header format, goal = uniformly random node at
    shortest-path distance >= min_dist from start (any colours), so reaching it is not guaranteed by rule-structured
    walks.  Only the header is meaningful (no demonstration); used for free-generation success only."""
    for _ in range(max_tries):
        labels, f = gen_graph(rng)
        start = rng.randint(N_NODES)
        dist = {start: 0}; frontier = [start]
        while frontier:
            nxt = []
            for v in frontier:
                for c in range(N_COL):
                    u = f[c, v]
                    if u not in dist:
                        dist[u] = dist[v] + 1; nxt.append(u)
            frontier = nxt
        far = [v for v, d in dist.items() if d >= min_dist]
        if not far:
            continue
        goal = far[rng.randint(len(far))]
        x = np.full(T, PAD, dtype=np.int64)
        x[0:4] = [GNAV, NODE0 + labels[goal], NODE0 + labels[start], SEP]
        edges = [(v, c) for v in range(N_NODES) for c in range(N_COL)]
        p = 4
        for e in rng.permutation(len(edges)):
            v, c = edges[e]
            x[p:p + 4] = [NODE0 + labels[v], COL0 + c, NODE0 + labels[f[c, v]], SEP]; p += 4
        return x, dict(labels=labels, f=f, start=start, goal=goal, dist=dist[goal])
    raise RuntimeError("no hard-goal instance")


def hardgoal_set(n, seed, min_dist=4):
    rng = np.random.RandomState(seed)
    xs, metas = zip(*[gen_hardgoal(rng, min_dist) for _ in range(n)])
    return np.stack(xs), list(metas)


def graph_batch(rng, B):
    xs, ms, metas = zip(*[gen_instance(rng) for _ in range(B)])
    return np.stack(xs), np.stack(ms), list(metas)


def parse_header(x):
    """Recover (label->local index, f, start, goal) from the header tokens alone (what a deployed verifier sees)."""
    goal_l, start_l = int(x[1]) - NODE0, int(x[2]) - NODE0
    lab = {}
    edges = {}
    for ch in range(1, HEADER_CHUNKS):
        v, c, u, _ = (int(t) for t in x[4 * ch:4 * ch + 4])
        edges[(v - NODE0, c - COL0)] = u - NODE0
    return edges, start_l, goal_l


def verify(x_header, hop_tokens):
    """Exact verifier. x_header: the first WALK_START tokens. hop_tokens: generated tokens after the header.
    Success iff every hop chunk is [colour, <to>, f_colour(cur), <sep>], a <done> chunk comes, the walk is at the goal
    then, and at most MAX_HOPS hops were taken. Returns (success, n_valid_hops, reached_goal, format_ok)."""
    edges, cur, goal = parse_header(x_header)
    hop_tokens = list(int(t) for t in hop_tokens)
    n = 0
    reached = False
    for ch in range(MAX_HOPS + 1):
        c4 = hop_tokens[4 * ch:4 * ch + 4]
        if len(c4) < 1:
            return False, n, reached, False
        if c4[0] == DONE:
            return (cur == goal and n > 0), n, reached, True
        if len(c4) < 4:
            return False, n, reached, False
        if HOP_FMT in ("src", "srcto"):
            src, c, u, term = c4
            if src != NODE0 + cur:
                return False, n, reached, False
            to = TO
            sep = SEP if term == (TO if HOP_FMT == "srcto" else SEP) else -1
        else:
            c, to, u, sep = c4
        if not (COL0 <= c < COL0 + N_COL and to == TO and sep == SEP and NODE0 <= u < NODE0 + N_NODE_TOK):
            return False, n, reached, False
        if edges.get((cur, c - COL0)) != u - NODE0:
            return False, n, reached, False
        cur = u - NODE0; n += 1
        reached = reached or cur == goal
    return False, n, reached, True


def fixed_graph_set(n, seed):
    rng = np.random.RandomState(seed)
    xs, ms, metas = graph_batch(rng, n)
    return xs, ms, metas


